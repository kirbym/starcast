import type { Kind } from './kind.ts'
import type { MoonPhase } from './report.ts'

/** Each Kind Sprite is a square grid this many pixels across, drawn at 5px per pixel: 150px. */
export const SPRITE_SIZE = 30

/** The grid character for a pixel left unpainted, so the card shows through. */
export const TRANSPARENT = '.'

/** The one palette every Kind Sprite draws from: the app's indigo, lavender and white tones
 * plus a few accents. Each grid character names one color. */
export const PALETTE = {
  W: '#ffffff', // white
  p: '#e8e6f0', // pale lavender-white, the app's text
  b: '#bcd4ff', // blue-white
  l: '#b3a4f2', // lavender
  v: '#7c6bd6', // violet
  i: '#45428f', // indigo
  d: '#272a5c', // deep indigo
  G: '#a9a6bd', // moon gray, the app's muted text
  g: '#6c6982', // crater gray
  a: '#f2b544', // amber
  r: '#c2603a', // rust
  t: '#45bfb0', // teal
  o: '#e586a6', // rose
} as const

export type PaletteColor = keyof typeof PALETTE

/** How a whole layer moves, each named after its `sprite-<motion>` class in index.css. They
 * change only opacity, or position by whole pixels, so every pixel stays crisp:
 * - twinkle: each star dims now and then, the stars at staggered times
 * - flicker: fades most of the way out and back
 * - pulse: fades out and back slowly
 * - breathe: dims a little and back, very slowly
 * - shimmer: wavers in brightness
 * - drift: steps a pixel down and to the left, then back, wavering
 * - nudge-up-right, nudge-down-left: steps a pixel that way, then back
 * - brighten: unseen while still, it fades in and out
 * - streak: steps eight pixels down and to the right, then hides until it starts again */
export type Motion =
  | 'twinkle'
  | 'flicker'
  | 'pulse'
  | 'breathe'
  | 'shimmer'
  | 'drift'
  | 'nudge-up-right'
  | 'nudge-down-left'
  | 'brighten'
  | 'streak'

/** How many frames a turning layer swaps through, its grid first. */
export const TURN_FRAMES = 4

/** One named layer of a Kind Sprite: SPRITE_SIZE rows of SPRITE_SIZE characters, each a
 * PALETTE key or TRANSPARENT. Layers paint in order, later ones over earlier ones, and stay
 * separate so a layer can be animated on its own. */
export interface SpriteLayer {
  name: string
  /** How the whole layer moves; a layer without one holds still, unless it turns. */
  motion?: Motion
  /** The layer's frame when the sprite holds still, under prefers-reduced-motion: reduce. */
  grid: string[]
  /** A turning layer's other frames, which it swaps through after its grid. Turning motion
   * swaps frames, since rotating pixel art blurs it. */
  frames?: string[][]
}

/** Every frame a layer shows: its grid, then any turning frames. */
export function framesOf(layer: SpriteLayer): string[][] {
  return [layer.grid, ...(layer.frames ?? [])]
}

export interface Sprite {
  layers: SpriteLayer[]
}

/** The Moon's eight phases, in order from new Moon round to the waning crescent. */
export const MOON_PHASES = [
  'new',
  'waxing_crescent',
  'first_quarter',
  'waxing_gibbous',
  'full',
  'waning_gibbous',
  'last_quarter',
  'waning_crescent',
] as const

export type MoonPhaseName = (typeof MOON_PHASES)[number]

/** Which of the eight phases the Moon is drawn as. Each takes the fractions nearest its own: the
 * boundaries fall midway between the phases' elongations from the Sun (every 45°), where
 * illuminated fraction = (1 − cos elongation) / 2. */
export function moonPhaseName({ illuminated_fraction: lit, waxing }: MoonPhase): MoonPhaseName {
  if (lit < 0.04) return 'new'
  if (lit >= 0.96) return 'full'
  if (lit < 0.31) return waxing ? 'waxing_crescent' : 'waning_crescent'
  if (lit < 0.69) return waxing ? 'first_quarter' : 'last_quarter'
  return waxing ? 'waxing_gibbous' : 'waning_gibbous'
}

