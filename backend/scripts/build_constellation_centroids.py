"""Derive the J2000 Centroid of each of the 88 IAU Named Constellations.

Run from backend/:  uv run scripts/build_constellation_centroids.py

The IAU boundaries (Delporte 1930, as digitised by Roman 1987) ship with Astropy, which reads them
in `get_constellation()`. This script covers the sphere with an equal-area Fibonacci lattice,
labels every point with its constellation, and averages each constellation's unit vectors. The
result is the area-weighted centre of the constellation on the sphere, in J2000 (ICRS).
See docs/research/constellation-centroids.md.
"""

import csv
import sys
from pathlib import Path

import astropy
import astropy.units as u
import numpy as np
from astropy.coordinates import SkyCoord, get_constellation

POINTS = 2_000_000
OUTPUT = Path(__file__).resolve().parent.parent / "app" / "data" / "constellations.csv"

# Astropy spells names in plain ASCII; use the IAU's own spelling where it differs.
IAU_SPELLING = {"Bootes": "Boötes"}


def fibonacci_lattice(count: int) -> tuple[np.ndarray, np.ndarray]:
    """Equal-area points on the unit sphere, as RA and Dec in radians."""
    index = np.arange(count)
    z = 1 - (2 * index + 1) / count
    golden_angle = np.pi * (3 - np.sqrt(5))
    return np.mod(index * golden_angle, 2 * np.pi), np.arcsin(z)


def main() -> None:
    ra, dec = fibonacci_lattice(POINTS)
    points = SkyCoord(ra=ra * u.rad, dec=dec * u.rad, frame="icrs")
    abbreviations = get_constellation(points, short_name=True)
    names = get_constellation(points)

    vectors = np.column_stack([np.cos(dec) * np.cos(ra), np.cos(dec) * np.sin(ra), np.sin(dec)])
    rows = []
    for abbreviation in sorted(set(abbreviations)):
        members = abbreviations == abbreviation
        x, y, z = vectors[members].sum(axis=0)
        centroid_ra = np.degrees(np.arctan2(y, x)) % 360
        centroid_dec = np.degrees(np.arctan2(z, np.hypot(x, y)))
        name = str(names[members][0]).strip()
        rows.append(
            {
                "key": abbreviation.lower(),
                "abbreviation": abbreviation,
                "name": IAU_SPELLING.get(name, name),
                "ra_hours": f"{centroid_ra / 15:.4f}",
                "dec_degrees": f"{centroid_dec:.3f}",
                "area_square_degrees": f"{members.sum() * 41252.96 / POINTS:.0f}",
            }
        )
    if len(rows) != 88:
        sys.exit(f"expected 88 constellations, found {len(rows)}")

    OUTPUT.parent.mkdir(exist_ok=True)
    with OUTPUT.open("w", newline="", encoding="utf-8") as file:
        file.write(
            "# Centroids (J2000) of the 88 IAU constellations, generated by "
            "scripts/build_constellation_centroids.py\n"
            f"# from the IAU boundaries in Astropy {astropy.__version__} "
            f"(BSD-3-Clause), sampled at {POINTS:,} equal-area points.\n"
        )
        writer = csv.DictWriter(file, fieldnames=list(rows[0]), lineterminator="\n")
        writer.writeheader()
        writer.writerows(rows)
    print(f"wrote {len(rows)} constellations to {OUTPUT}")


if __name__ == "__main__":
    main()
